"""T-39301: generate the engine's name/address and stack-frame tables.

usage: python3 -I tools/port/gen_engine_tables.py --repo <repo root> --asm <asm dir> --out port/godot/engine

Writes (deterministic, generated, do not edit):
  _symbols.gd      FUNCTIONS: C function name -> address, from `type:func` lines of config/symbol_addrs*.txt
  _frame_sizes.gd  FRAME_SIZES: function -> bytes its prologue subtracts from sp (`addiu $sp, $sp, -N`, 0 for a
                   leaf), FUNCTION_SIZES: function -> byte size (the symbol file's size: or the asm extent)
The asm directory is the build's split output (asm/*.s, asm/matchings/main/<file>/<function>.s); it is derived from
the user's executable and is not committed, but the numbers extracted here are frame facts of the compiled code.
Only the asm of the main executable (not overlays) is read.
"""
import argparse
import glob
import os
import re

ADDI = re.compile(r'addiu\s+\$sp,\s*\$sp,\s*(-?)(0x[0-9A-Fa-f]+|\d+)')
INSN = re.compile(r'/\*\s*[0-9A-F]+\s+([0-9A-F]{8})\s+[0-9A-F]{8}\s*\*/')


def parse_asm(paths):
    frames, extents = {}, {}
    for path in paths:
        name = None
        first = last = None
        frame = None
        for line in open(path, errors='ignore'):
            if line.startswith('glabel '):
                name = line.split()[1]
                first = last = None
                frame = None
                continue
            if line.startswith('endlabel '):
                if name:
                    frames[name] = frame or 0
                    if first is not None:
                        extents[name] = last + 4 - first
                name = None
                continue
            if name:
                m = INSN.search(line)
                if m:
                    address = int(m.group(1), 16)
                    first = address if first is None else first
                    last = address
                a = ADDI.search(line)
                if a and frame is None and a.group(1) == '-':
                    frame = int(a.group(2), 0)
    return frames, extents


def parse_symbols(files):
    funcs, sizes = {}, {}
    pat = re.compile(r'^(\w+)\s*=\s*(0x[0-9A-Fa-f]+);\s*//(.*)$')
    for path in files:
        for line in open(path):
            m = pat.match(line.strip())
            if not m or 'type:func' not in m.group(3):
                continue
            funcs[m.group(1)] = int(m.group(2), 16)
            s = re.search(r'size:(0x[0-9A-Fa-f]+)', m.group(3))
            if s:
                sizes[m.group(1)] = int(s.group(1), 16)
    return funcs, sizes


def emit(path, title, tables):
    with open(path, 'w') as out:
        out.write('extends RefCounted\n## GENERATED by tools/port/gen_engine_tables.py (T-39301). Do not edit; regenerate and commit.\n')
        out.write('## %s\n\n' % title)
        for const, table, fmt in tables:
            out.write('const %s: Dictionary = {\n' % const)
            for key in sorted(table):
                out.write('\t"%s": %s,\n' % (key, fmt % table[key]))
            out.write('}\n\n')


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--repo', required=True)
    p.add_argument('--asm', required=True)
    p.add_argument('--out', required=True)
    args = p.parse_args()
    symbol_files = sorted(glob.glob(os.path.join(args.repo, 'config', 'symbol_addrs*.txt')))
    funcs, sizes = parse_symbols(symbol_files)
    paths = sorted(glob.glob(os.path.join(args.asm, '*.s')) + glob.glob(os.path.join(args.asm, 'matchings', 'main', '*', '*.s')))
    frames, extents = parse_asm(paths)
    # unnamed functions (func_80087954, ...) are named after their address
    for name in frames:
        m = re.fullmatch(r'func_([0-9A-Fa-f]{8})', name)
        if m and name not in funcs:
            funcs[name] = int(m.group(1), 16)
    frames = {k: v for k, v in frames.items() if k in funcs}
    fsizes = {k: sizes.get(k, extents.get(k)) for k in funcs if sizes.get(k) or extents.get(k)}
    emit(os.path.join(args.out, '_symbols.gd'),
         'C function name -> PS1 code address (config/symbol_addrs*.txt, type:func): %d functions.' % len(funcs),
         [('FUNCTIONS', funcs, '0x%08X')])
    emit(os.path.join(args.out, '_frame_sizes.gd'),
         'Stack frame bytes (FRAME_SIZES) and code size (FUNCTION_SIZES) of main-executable functions: %d with a frame entry.' % len(frames),
         [('FRAME_SIZES', frames, '0x%X'), ('FUNCTION_SIZES', fsizes, '0x%X')])
    print('%d functions, %d frame entries, %d sizes' % (len(funcs), len(frames), len(fsizes)))


main()
