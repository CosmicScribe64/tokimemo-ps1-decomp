# Capital height in rows, from the glyph data (top row to the baseline row inclusive).
CAP_HEIGHT = len(LARGE['H'][1])


def large_glyph(character):
    """Upright mask points and width for one port-made glyph; fails closed on malformed data."""
    if character == ' ':
        return {'points': [], 'width': SPACE}
    top, rows = LARGE[character]
    if len({len(r) for r in rows}) != 1 or set(''.join(rows)) - {'#', '.'} or top + len(rows) > LARGE_HEIGHT:
        raise ValueError('malformed port-made glyph: ' + character)
    return {'points': [(x, top + y) for y, row in enumerate(rows) for x, cell in enumerate(row) if cell == '#'],
            'width': len(rows[0])}
