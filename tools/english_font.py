#!/usr/bin/env python3
"""Compile the English proportional font into assembly data and a width table (T-39502).

Usage (in Docker, run by ninja for the `english` target):
    python3 tools/english_font.py translations/en/font/latin12.txt build/en/gen/english_font.s \
        build/en/font_metrics.json

Input: the text bitmap described at the top of the font file (`glyph 0xNN name` and 12 rows of
`.`/`#` per glyph). Outputs:
  - an assembly data file for the English island (src/english/text.c reads it): `english_font_index[256]` maps a
    single-byte code to a glyph number (0xFF: no glyph), `english_font_advance[]` holds each glyph's
    advance in pixels, and `english_font_glyphs[]` the bitmaps in the game's own 18-byte format
    (12 x 12 pixels, 1 bit per pixel, rows of 12 bits packed MSB first, as `text_glyph_expand` reads);
  - a JSON width table (`{"advance": {"0x41": 6, ...}, "sjis_advance": 14, "line_height": 16}`) for
    the build-time word wrap of the text writers (T-39503).
Exits non-zero on a malformed glyph, a duplicate code or a code outside 0x20-0x7E / 0xA0-0xAF.
Codes 0xB0-0xDF are reserved for persistent player-name letter pairs (T-39506).
"""
import json
import os
import sys

ROWS = 12
MAX_WIDTH = 12
SJIS_ADVANCE = 14  # text_state.glyph_advance after text_system_reset; 16 on the name entry screen
LINE_HEIGHT = 16   # row step of talk_render and the menus


def valid_code(code):
    return 0x20 <= code <= 0x7E or 0xA0 <= code <= 0xAF


def parse(path):
    """[(code, name, rows, advance)] in file order."""
    glyphs = []
    lines = open(path, encoding="utf-8").read().split("\n")
    i = 0
    seen = set()
    while i < len(lines):
        line = lines[i].strip()
        i += 1
        if not line or line.startswith("#"):
            continue
        words = line.split()
        if words[0] != "glyph" or len(words) < 3:
            sys.exit("%s:%d: expected `glyph 0xNN name`, got %r" % (path, i, line))
        code = int(words[1], 16)
        advance = None
        if words[-1].startswith("advance="):
            advance = int(words[-1][len("advance="):])
            words = words[:-1]
        name = " ".join(words[2:])
        if not valid_code(code):
            sys.exit("%s:%d: code 0x%02X is outside 0x20-0x7E and 0xA0-0xAF (name-pair range reserved)" % (path, i, code))
        if code in seen:
            sys.exit("%s:%d: code 0x%02X defined twice" % (path, i, code))
        seen.add(code)
        rows = [r.strip() for r in lines[i:i + ROWS]]
        i += ROWS
        width = len(rows[0]) if rows else 0
        if len(rows) != ROWS or any(len(r) != width or set(r) - set(".#") for r in rows):
            sys.exit("%s: glyph 0x%02X: need %d rows of `.`/`#`, all the same width" % (path, code, ROWS))
        if not 1 <= width <= MAX_WIDTH:
            sys.exit("%s: glyph 0x%02X: width %d is not 1-%d" % (path, code, width, MAX_WIDTH))
        if advance is None:
            advance = width + 1
        if not 1 <= advance <= 16:
            sys.exit("%s: glyph 0x%02X: advance %d is not 1-16" % (path, code, advance))
        glyphs.append((code, name, rows, advance))
    if len(glyphs) > 0xFF:
        sys.exit("%s: %d glyphs, the index table holds 255" % (path, len(glyphs)))
    return glyphs


def pack(rows):
    """18 bytes: 144 bits, row-major, MSB first, 12 bits per row."""
    bits = []
    for row in rows:
        bits += [1 if c == "#" else 0 for c in row.ljust(MAX_WIDTH, ".")]
    out = bytearray(18)
    for n, b in enumerate(bits):
        if b:
            out[n >> 3] |= 0x80 >> (n & 7)
    return bytes(out)


def main(argv):
    if len(argv) != 4:
        sys.exit(__doc__)
    src, s_out, json_out = argv[1:]
    glyphs = parse(src)
    index = [0xFF] * 256
    for n, (code, _name, _rows, _adv) in enumerate(glyphs):
        index[code] = n
    bitmaps = b"".join(pack(rows) for _c, _n, rows, _a in glyphs)
    advances = bytes(a for _c, _n, _r, a in glyphs)
    for path in (s_out, json_out):
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(s_out, "w") as f:
        f.write("# Generated by tools/english_font.py from %s (T-39502). Do not edit.\n" % src)
        f.write(".section .data\n")
        for label, comment, data in (
                ("english_font_index", "single-byte code -> glyph number, 0xFF: no glyph", bytes(index)),
                ("english_font_advance", "advance in pixels per glyph number", advances),
                ("english_font_glyphs", "18-byte 12 x 12 1bpp bitmaps per glyph number", bitmaps)):
            f.write("\n# %s\n.globl %s\n.type %s, @object\n%s:\n" % (comment, label, label, label))
            for k in range(0, len(data), 16):
                f.write("    .byte %s\n" % ", ".join("0x%02X" % b for b in data[k:k + 16]))
            f.write(".size %s, %d\n.balign 4\n" % (label, len(data)))
    with open(json_out, "w") as f:
        json.dump({"source": src, "line_height": LINE_HEIGHT, "sjis_advance": SJIS_ADVANCE,
                   "advance": {"0x%02X" % c: a for c, _n, _r, a in glyphs}}, f, indent=1, sort_keys=True)
        f.write("\n")
    print("english_font: %d glyphs, %d bytes of bitmaps" % (len(glyphs), len(bitmaps)))


if __name__ == "__main__":
    main(sys.argv)
