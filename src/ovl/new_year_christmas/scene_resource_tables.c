void new_year_status_and_dialogue_route(void) {
    game_state.day_event_done_bits |= 8;
    if ((u32)((u8)get_g_zyotai_s(game_state.current_girl) & 0x7F) >= 2U) {
        game_state.mode_step += 8;
        return;
    }
    if (game_state.current_girl == GIRL_SHIORI && new_year_shiori_route_flag == 1) {
        event_log_add(0xD, 0x2D);
    } else {
        event_log_add(0xD, 0x2C);
    }
    game_state.day_event_done_bits |= 4;
    new_year_dialogue_text_table = D_80143A70;
    new_year_dialogue_command_table = D_80143AAC;
    new_year_dialogue_voice_table = D_80143AE8;
    new_year_dialogue_group = 0;
    new_year_dialogue_line = 0;
    portrait_layout_set(get_g_zyotai_h(game_state.current_girl));
    mode_step_next();
}

