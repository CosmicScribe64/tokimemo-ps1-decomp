void new_year_birthday_gate(void) {
    s32 r;

    r = get_g_zyotai_s(game_state.current_girl);
    if ((game_state.day == ((u32)(game_state.girls[game_state.current_girl].birthday.w << 0x17) >> 0x1B)) &&
        (game_state.month == (game_state.girls[game_state.current_girl].birthday.w & 0xF)) &&
        (new_year_fallback_dialogue_flag == 0) &&
        (game_state.current_girl == GIRL_SHIORI)) {
        game_state.day_event_done_bits |= NEW_YEAR_GIRL_BIRTHDAY_DONE_BIT;
        game_state.mode_step += 4;
    /* FAKE: indirect reads of unk_040 and unk_0F8 prevent cross-branch CSE of unk_040 and match the ilod evaluation order of unk_1BC[] above, and the (u8) cast on r reserves the extra temp as in new_year_player_birthday_status_gate (T-2020); real source unknown. T-24080 */
    } else if ((*(u8 *)&game_state.day == ((u32)((*(s32 *)&game_state.player_birthday) << 0x17) >> 0x1B)) &&
               (game_state.month == ((*(s32 *)&game_state.player_birthday) & 0xF)) &&
               (new_year_fallback_dialogue_flag == 0)) {
        if ((u32)((u8)r & 0x7F) < 2U) {
            game_state.day_event_done_bits |= NEW_YEAR_PLAYER_BIRTHDAY_LOW_STATUS_BIT;
            game_state.mode_step += 0x1B;
        } else {
            game_state.day_event_done_bits |= NEW_YEAR_PLAYER_BIRTHDAY_OTHER_STATUS_BIT;
        }
    }
    mode_step_next();
}

void new_year_dialogue_group_selector_update(void) {
    u32 girl;
    u8 status;

    /* FAKE: indirect flag reads keep the original reloads; the word-sized
     * girl copy preserves the comparison operand order. T-10010. */
    status = get_g_zyotai_s(game_state.current_girl) & 0x7F;
    if (status >= 2U) {
        new_year_dialogue_group += 2;
    }
    girl = new_year_best_rank_girl;
    if (game_state.year == 0x62) {
        new_year_dialogue_group += 1;
    } else if ((*(u8 *)&new_year_fallback_dialogue_flag == 0) && (game_state.current_girl == GIRL_MEGUMI) && (girl == 9) && (status < 2U)) {
        new_year_dialogue_group += 4;
    }
    if (*(u8 *)&new_year_fallback_dialogue_flag != 0) {
        new_year_dialogue_group = 0x13;
    }
    mode_step_next();
}

