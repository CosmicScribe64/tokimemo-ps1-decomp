s32 new_year_day_completion_apply(void) {
    if (game_state.substep == 0) {
        hud_day_bgm_load();
        game_state.substep++;
    }
    if (game_state.substep == 1) {
        if (game_state.mode_step_timer.u++ >= 0x400U) {
            cd_command_reset();
            audio_bank_state_reset();
            game_state.substep = 0;
        }
        if (audio_bank_load_poll() == 1) {
            game_state.substep += 1;
        } else {
            return 0;
        }
    }
    if (new_year_fallback_dialogue_flag == 0) {
        game_state.girls[game_state.current_girl].affection += 1;
    }
    check_para_limit();
    if (new_year_fallback_dialogue_flag == 0) {
        game_state.day_event_done_bits |= 8;
    }
    parameter_show_init();
    parameter_show_init();
    parameter_disp_switch(0);
    return day_event_next(1);
}

